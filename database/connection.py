"""
connection.py — SQLite database connection manager for MediVault.

Provides a DatabaseManager class that handles opening, closing, and
querying the SQLite database with automatic foreign-key enforcement.
"""

import sqlite3
import threading
import os
import re
from contextlib import contextmanager
from pathlib import Path
from typing import Any, Dict, Iterator, List, Optional, Tuple

from utils.logger import setup_logger

# Project root is one level above the 'database' package
BASE_DIR = Path(__file__).resolve().parent.parent

logger = setup_logger('medivault.db')


def _postgres_query(query: str) -> str:
    """Translate the small SQLite SQL dialect used by services to PostgreSQL."""
    query = query.replace('?', '%s')
    ignore_insert = bool(re.match(r"\s*INSERT\s+OR\s+IGNORE\s+INTO", query, flags=re.IGNORECASE))
    query = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", query, flags=re.IGNORECASE)
    if ignore_insert and "ON CONFLICT" not in query.upper():
        returning = re.search(r"\s+RETURNING\s+", query, flags=re.IGNORECASE)
        if returning:
            query = query[:returning.start()] + " ON CONFLICT DO NOTHING" + query[returning.start():]
        else:
            query = query.rstrip().rstrip(';') + " ON CONFLICT DO NOTHING"
    query = query.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    query = re.sub(r"DEFAULT\s+\(datetime\('now',\s*'localtime'\)\)", "DEFAULT CURRENT_TIMESTAMP", query, flags=re.IGNORECASE)
    query = re.sub(r"DATE\(([^()]+)\)", r"CAST(\1 AS DATE)", query, flags=re.IGNORECASE)
    return query


class _PostgresCursor:
    """Cursor compatibility wrapper for existing service code."""

    def __init__(self, cursor):
        self._cursor = cursor

    def execute(self, query, params=()):
        self._cursor.execute(_postgres_query(query), params)
        return self

    def executemany(self, query, params_list):
        self._cursor.executemany(_postgres_query(query), params_list)
        return self

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    @property
    def rowcount(self):
        return self._cursor.rowcount

    @property
    def lastrowid(self):
        return None


class _PostgresConnection:
    """Small connection wrapper retaining DatabaseManager's existing API."""

    def __init__(self, connection):
        self._connection = connection

    def cursor(self):
        return _PostgresCursor(self._connection.cursor())

    def execute(self, query, params=()):
        return _PostgresCursor(self._connection.execute(_postgres_query(query), params))

    def executemany(self, query, params_list):
        return _PostgresCursor(self._connection.cursor().executemany(_postgres_query(query), params_list))

    def commit(self):
        self._connection.commit()

    def rollback(self):
        self._connection.rollback()

    def close(self):
        self._connection.close()


class DatabaseManager:
    """
    Manages a single SQLite connection with convenience helpers.

    Usage:
        db = DatabaseManager()              # uses default path
        db = DatabaseManager('data/test.db')

        # As a context manager (auto-closes on exit):
        with DatabaseManager() as db:
            rows = db.fetchall("SELECT * FROM medicines")
    """

    def __init__(self, db_path: str = "data/medivault.db") -> None:
        """
        Initialise the manager.

        Args:
            db_path: Database file path relative to the project root.
        """
        configured_path = os.environ.get("MEDIVAULT_DB_PATH")
        self.db_path: Path = Path(configured_path) if configured_path else BASE_DIR / db_path
        # Ensure the parent directory exists (e.g. 'data/')
        self.db_path.parent.mkdir(parents=True, exist_ok=True)
        # Connection is created lazily by get_connection()
        self._connection: Optional[sqlite3.Connection] = None
        self._postgres = bool(os.environ.get("DATABASE_URL"))
        self._lock = threading.RLock()
        logger.debug("DatabaseManager initialised — path: %s", self.db_path)

    # ------------------------------------------------------------------
    # Connection management
    # ------------------------------------------------------------------
    def get_connection(self) -> sqlite3.Connection:
        """
        Return an open SQLite connection, creating one if necessary.

        The connection uses sqlite3.Row as row_factory so that rows
        behave like dictionaries. Foreign-key enforcement is enabled.

        Returns:
            An open sqlite3.Connection.
        """
        with self._lock:
            if self._connection is None:
                if self._postgres:
                    import psycopg
                    from psycopg.rows import dict_row

                    connection = psycopg.connect(os.environ["DATABASE_URL"], row_factory=dict_row)
                    self._connection = _PostgresConnection(connection)
                else:
                    self._connection = sqlite3.connect(str(self.db_path), check_same_thread=False)
            # Rows accessible by column name
                if not self._postgres:
                    self._connection.row_factory = sqlite3.Row
                    self._connection.execute("PRAGMA foreign_keys = ON")
                logger.debug("Opened database connection: %s", self.db_path)
            return self._connection

    def close(self) -> None:
        """Close the database connection if it is open."""
        with self._lock:
            if self._connection is not None:
                self._connection.close()
                self._connection = None
                logger.debug("Closed database connection.")

    # ------------------------------------------------------------------
    # Query helpers
    # ------------------------------------------------------------------
    def execute(self, query: str, params: Tuple = ()):
        """
        Execute a single SQL statement and commit.

        Args:
            query:  SQL query string with '?' placeholders.
            params: Tuple of parameters to bind.

        Returns:
            The sqlite3.Cursor after execution.
        """
        with self._lock:
            conn = self.get_connection()
            cursor = conn.execute(query, params)
            conn.commit()
            return cursor

    def executemany(self, query: str, params_list: List[Tuple]):
        """
        Execute a SQL statement for each set of parameters and commit.

        Args:
            query:       SQL query string with '?' placeholders.
            params_list: List of parameter tuples.

        Returns:
            The sqlite3.Cursor after execution.
        """
        with self._lock:
            conn = self.get_connection()
            cursor = conn.executemany(query, params_list)
            conn.commit()
            return cursor

    @contextmanager
    def transaction(self) -> Iterator[sqlite3.Connection]:
        """Run multiple statements as one commit-or-rollback unit."""
        with self._lock:
            conn = self.get_connection()
            try:
                yield conn
                conn.commit()
            except Exception:
                conn.rollback()
                raise

    def fetchone(self, query: str, params: Tuple = ()) -> Optional[Dict[str, Any]]:
        """
        Execute a query and return the first row as a dict, or None.

        Args:
            query:  SQL query string.
            params: Tuple of parameters.

        Returns:
            A dict representing the row, or None if no rows matched.
        """
        with self._lock:
            conn = self.get_connection()
            cursor = conn.execute(query, params)
            row = cursor.fetchone()
            if row is None:
                return None
            return dict(row)

    def fetchall(self, query: str, params: Tuple = ()) -> List[Dict[str, Any]]:
        """
        Execute a query and return all rows as a list of dicts.

        Args:
            query:  SQL query string.
            params: Tuple of parameters.

        Returns:
            List of dicts (one per row).  Empty list if no rows.
        """
        with self._lock:
            conn = self.get_connection()
            cursor = conn.execute(query, params)
            return [dict(row) for row in cursor.fetchall()]

    # ------------------------------------------------------------------
    # Context-manager support
    # ------------------------------------------------------------------
    def __enter__(self) -> "DatabaseManager":
        """Enter the context — return self."""
        return self

    def __exit__(self, exc_type, exc_val, exc_tb) -> None:
        """Exit the context — close the connection."""
        self.close()
